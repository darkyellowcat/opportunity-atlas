// Generate stable, shareable HTML from the same catalog used by the browser.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const project = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const root = fs.existsSync(path.join(project, 'programs.js')) ? project : path.join(project, 'dist');
const out = path.join(root, 'opportunities');
const context = vm.createContext({ window: { addEventListener() {} } });
for (const name of ['catalog.js', 'programs.js', 'additions.js', 'extras.js', 'shared.js']) {
  vm.runInContext(fs.readFileSync(path.join(root, name), 'utf8'), context, { filename: name });
}
const atlas = context.window.Atlas;
const items = atlas.items();
const shell = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const escaped = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const esc = value => String(value ?? '').replace(/[&<>"']/g, ch => escaped[ch]);
const brand = '机会路标';
const signature = '<!-- Generated by tools/build-details.mjs -->';
const ids = new Set(['index']);
const outputs = new Map();

function officialLink(link, css = '') {
  if (!['https:', 'http:'].includes(new URL(link.url).protocol)) throw new Error('无效外链：' + link.url);
  return '<a class="' + css + '" href="' + esc(link.url) + '" rel="noopener noreferrer">' + esc(link.label) + '</a>';
}

function facts(item) {
  const fields = [['参与资格', item.audience], ['报名渠道', item.entry], ['个人 / 组队', item.team],
    ['时间投入', item.effort], ['产出与交付', item.delivery], ['参与方式', item.mode], ['费用与支持', item.cost]];
  return '<dl class="facts">' + fields.map(([name, value]) =>
    '<div><dt>' + name + '</dt><dd>' + esc(value || '官方未说明') + '</dd></div>'
  ).join('') + '</dl>';
}

function timeMarkup(value, timezone) {
  return '<time datetime="' + esc(value) + '">' + esc(atlas.dateLabel({start: value, timezone})) + '</time>';
}

function timeline(events) {
  if (!events?.length) return '<p>本条暂未收录已核实的具体日期。</p>';
  return '<ul class="event-list">' + events.map(event => {
    const end = event.end && event.end !== event.start ? ' 至 ' + timeMarkup(event.end, event.timezone) : '';
    const scope = event.scope ? ' · ' + esc(event.scope) : '';
    return '<li><div><strong>' + esc(event.title) + '</strong><br>' + timeMarkup(event.start, event.timezone) + end + scope + '</div></li>';
  }).join('') + '</ul>';
}

function detail(item) {
  return [
    '<nav class="crumbs" aria-label="当前位置"><a href="opportunities/index.html">活动索引</a> / 机会详情</nav>',
    '<header class="reading-head page-head"><p class="eyebrow">' + esc([item.kind, item.contestFormat, item.region].filter(Boolean).join(' · ')) + '</p><h1>' + esc(item.title) + '</h1><p>' + esc(item.parent) + ' · ' + esc(item.edition) + '</p><div class="tag-list">' +
    item.topics.map(t => '<span class="tag">' + esc(t) + '</span>').join('') + '</div></header>',
    '<div class="with-aside"><div><section class="panel"><h2>你会做什么</h2><p>' + esc(item.summary) + '</p>',
    '<div class="trial-panel"><h3>先试一下</h3><p>' + esc(item.try.note) + '</p>' + officialLink(item.try, 'btn btn-primary') + '</div></section>',
    '<section class="panel"><h2>参与条件</h2>' + facts(item) + '</section>',
    '<section class="panel"><h2>官方日程</h2>' + timeline(item.events) + '</section></div>',
    '<aside><section class="sidebar-panel"><h2>核验时的安排</h2><p>' + esc(item.status) +
    '</p><p>' + esc(item.statusNote) + '</p><p>人工核验于 ' + timeMarkup(item.checked) + '</p></section>',
    '<section class="sidebar-panel"><h2>官方来源</h2><ul>' + item.sources.map(s => '<li>' + officialLink(s) + '</li>').join('') + '</ul></section></aside></div>'
  ].join('\n');
}

function page(slug, heading, description, contents, isIndex = false) {
  const title = heading + ' · ' + brand;
  const metadata = [
    '<base href="../">',
    '<meta name="description" content="' + esc(description) + '">',
    '<meta property="og:locale" content="zh_CN">',
    '<meta property="og:type" content="' + (isIndex ? 'website' : 'article') + '">',
    '<meta property="og:site_name" content="' + brand + '">',
    '<meta property="og:title" content="' + esc(title) + '">',
    '<meta property="og:description" content="' + esc(description) + '">',
    '<meta name="twitter:card" content="summary">'
  ].join('\n  ');
  if (!/<main\b[^>]*id="app"[^>]*>/.test(shell)) throw new Error('首页缺少 #app 容器');
  let html = shell.replace('<html ', signature + '\n<html ')
    .replace(/<meta name="description"[^>]*>/, () => metadata)
    .replace(/<title>[\s\S]*?<\/title>/, () => '<title>' + esc(title) + '</title>')
    .replace(/\s*<template id="home-hero">[\s\S]*?<\/template>/, '')
    .replace(/<a class="skip-link" href="#app"/, '<a class="skip-link" href="opportunities/' + slug + '.html#app"')
    .replace(/<main\b([^>]*id="app"[^>]*)>[\s\S]*?<\/main>/, (_whole, attrs) => {
      const target = isIndex ? '' : ' data-detail="' + slug + '"';
      return '<main' + attrs + target + '>\n' + contents + '\n  </main>';
    });
  if (isIndex) html = html.replace(/\s*<script defer src="[^"]+"><\/script>/g, '');
  return html;
}

for (const item of items) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(item.id) || ids.has(item.id)) {
    throw new Error('无效或重复的条目标识：' + item.id);
  }
  ids.add(item.id);
  outputs.set(item.id + '.html', page(item.id, item.title, item.summary, detail(item)));
}
const indexRows = items.map(i => '<li><a href="opportunities/' + i.id + '.html">' + esc(i.title) + '</a> · ' + esc(i.parent) + ' · ' + esc(i.edition) + '</li>').join('\n');
outputs.set('index.html', page('index', '全部机会', '按条目查阅机会路标收录的竞赛、科研与开源机会。',
  '<header class="page-head"><h1>全部机会</h1><p>共 ' + items.length + ' 项，可直接打开活动详情。</p></header><section class="panel"><ul>' + indexRows + '</ul></section>', true));

fs.mkdirSync(out, {recursive: true});
for (const [filename, html] of outputs) {
  const filenameOnDisk = path.join(out, filename);
  if (!fs.existsSync(filenameOnDisk) || fs.readFileSync(filenameOnDisk, 'utf8') !== html) {
    fs.writeFileSync(filenameOnDisk, html, 'utf8');
  }
}
for (const name of fs.readdirSync(out)) {
  if (name.endsWith('.html') && !outputs.has(name) && fs.readFileSync(path.join(out, name), 'utf8').includes(signature)) {
    fs.unlinkSync(path.join(out, name));
  }
}
console.log('已生成 ' + items.length + ' 个独立详情页和静态索引。');
